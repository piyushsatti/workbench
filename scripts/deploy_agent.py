#!/usr/bin/env python3
"""Deploy the shared agent config in agent/ to this machine's harness homes.

Dry run by default: prints what would change and writes nothing. `--apply` copies.
Real copies, never symlinks (links fail silently).
Executables land outside agent-writable source paths (~/.agents/bin is the only target here).
Skills in agent/skills/ copy to ~/.agents/skills (and ~/.claude/skills for Claude Code) without their tests, bin/,
runtime/ or install.json; a skill's install.json places its executables like a plugin's.

Plugin executables listed in each plugin repo's install.json are copied the same way (`files`); a `build`
entry is printed for the user to run, never run here. A third-party plugin's install.json (one whose GitHub owner
is not the catalog's) is never read: someone else's repo does not get to write into this home folder.

`--harness claude,codex,cursor,opencode` (default: all four) picks the harness destinations. The shared
~/.agents files and plugin executables deploy whatever the filter says.
- Claude Code: subagents copied as they are to ~/.claude/agents.
- Codex: subagents converted to TOML in ~/.codex/agents; agent/AGENTS.md copied to ~/.codex/AGENTS.md,
  because Codex reads that file's literal text and follows no imports or pointers.
- Cursor: subagents converted to Cursor frontmatter in ~/.cursor/agents. User Rules live in Cursor's
  settings, not a file, so they are only reported.
- OpenCode: subagents converted to OpenCode frontmatter in ~/.config/opencode/agents; agent/AGENTS.md
  copied to ~/.config/opencode/AGENTS.md, its global rules file. Skills need nothing more: it reads
  ~/.agents/skills.
See agent/docs/harness-parity.md for the sources.

Never written, only checked: ~/.claude/CLAUDE.md (its format is the user's; it must import the canonical rules),
the status line and CLAUDE_CODE_PLUGIN_DIRS in ~/.claude/settings.json (harness/claude's install.json puts the
status line in ~/.local/bin and the cc-status mod in ~/.local/share/claude-mods),
a ~/.agents/AGENTS.md, ~/.codex/AGENTS.md or ~/.config/opencode/AGENTS.md with its own content, and every settings file (hooks, permissions and sandbox
profiles are merged by hand per repository).
"""

import argparse
import filecmp
import functools
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import plugin_repos  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
AGENT = ROOT / "agent"
# The plugin repos come from plugins.json, as siblings of this repo. Tests set PLUGINS
# to a folder of plugin folders instead.
PLUGINS = None
# The repo's own tools (agent-tmux, workspaces, snippets, workbench CLI) live here, not as plugins.
TOOLS = ROOT / "tools"
# Harness extensions (harness/claude, …) live here, not under tools/.
HARNESS_MODS = ROOT / "harness"
HOME = Path.home()
HARNESSES = ("claude", "codex", "cursor", "opencode")

# source (relative to agent/) -> destination (relative to $HOME); directories copy file by file.
# Shared: every harness reads these, so they deploy regardless of --harness.
TARGETS = [
    ("bin", ".agents/bin"),
    ("docs", ".agents/docs"),
    ("skills", ".agents/skills"),
]
# What a skill folder keeps in the repo: its tests, and what its install.json puts outside agent-writable paths.
SKILL_STAYS = {"tests", "bin", "runtime", "install.json", "__pycache__"}
SHIM = "@~/.agents/AGENTS.md"
# What ~/.claude/settings.json needs for harness/claude: the status line, and the mods it loads.
STATUSLINE = "$HOME/.local/bin/claude-statusline"
MOD_DIRS = ["~/.local/share/claude-mods/cc-status"]
GENERATED = "Generated by workbench/scripts/deploy_agent.py from agent/{src}. Edit the source, not this file."
# Claude tools that write files; an agent with a tools list and none of these is read-only.
WRITE_TOOLS = {"Write", "Edit", "MultiEdit", "NotebookEdit"}


def unquote(value):
    """A YAML scalar written in one matching pair of quotes, unquoted: 'it''s' is it's, "a \\"b\\"" is a "b".
    Anything else, a value that only starts or ends with a quote included, is kept as written."""
    if len(value) >= 2 and value[0] == value[-1] == "'":
        inner = value[1:-1]
        if "'" not in inner.replace("''", ""):
            return inner.replace("''", "'")
    elif len(value) >= 2 and value[0] == value[-1] == '"':
        try:
            return json.loads(value)
        except ValueError:
            pass
    return value


def frontmatter(text):
    """(fields, body) of a Claude subagent file. Handles `key: value` and `key: >-` / `|` blocks."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("no frontmatter")
    end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    fields, key = {}, None
    for line in lines[1:end]:
        if key and (line.startswith((" ", "\t")) or not line.strip()):
            fields[key].append(line.strip())
            continue
        name, _, value = line.partition(":")
        key, value = name.strip(), value.strip()
        if value in (">", ">-", "|", "|-"):
            fields[key] = []
        else:
            fields[key] = unquote(value)
            key = None
    for name, value in fields.items():
        if isinstance(value, list):
            fields[name] = " ".join(part for part in value if part)
    return fields, "\n".join(lines[end + 1:]).strip("\n") + "\n"


def tools_of(fields):
    return {t.strip() for t in fields["tools"].split(",") if t.strip()} if "tools" in fields else None


def to_codex(src, text):
    """Claude subagent -> Codex custom agent TOML (name, description, developer_instructions).

    `model` is dropped (Claude aliases mean nothing to Codex; it inherits the parent's). Codex has no
    per-tool allowlist and ignores sandbox_mode in agent files, so `tools` maps only to
    `features.shell_tool = false` when Bash is absent from it.
    """
    fields, body = frontmatter(text)
    out = [f"# {GENERATED.format(src=src)}",
           f"name = {json.dumps(fields['name'], ensure_ascii=False)}",
           f"description = {json.dumps(fields.get('description', ''), ensure_ascii=False)}"]
    if "'''" in body:
        out.append(f"developer_instructions = {json.dumps(body, ensure_ascii=False)}")
    else:
        out.append(f"developer_instructions = '''\n{body}'''")
    tools = tools_of(fields)
    if tools is not None and "Bash" not in tools:
        out += ["", "[features]", "shell_tool = false"]
    return "\n".join(out) + "\n"


def to_cursor(src, text):
    """Claude subagent -> Cursor subagent markdown (name, description, model, readonly).

    `model: inherit` replaces Claude aliases; `readonly: true` when the Claude tools list has no
    file-writing tool. The body is unchanged.
    """
    fields, body = frontmatter(text)
    tools = tools_of(fields)
    readonly = tools is not None and not tools & WRITE_TOOLS
    head = ["---", f"# {GENERATED.format(src=src)}",
            f"name: {fields['name']}",
            f"description: {json.dumps(fields.get('description', ''), ensure_ascii=False)}",
            "model: inherit",
            f"readonly: {'true' if readonly else 'false'}",
            "---", ""]
    return "\n".join(head) + body


def to_opencode(src, text):
    """Claude subagent -> OpenCode agent markdown (description, mode, permission).

    The file name is the agent's name. `model` is dropped, so the subagent uses the model of the agent
    that called it. A Claude tools list without a file-writing tool denies `edit`, and one without Bash
    denies `bash`. The body is unchanged.
    """
    fields, body = frontmatter(text)
    tools = tools_of(fields)
    head = ["---", f"# {GENERATED.format(src=src)}",
            f"description: {json.dumps(fields.get('description', ''), ensure_ascii=False)}",
            "mode: subagent"]
    if tools is not None:
        denied = [k for k, absent in (("edit", not tools & WRITE_TOOLS), ("bash", "Bash" not in tools)) if absent]
        if denied:
            head += ["permission:"] + [f"  {k}: deny" for k in denied]
    return "\n".join(head + ["---", ""]) + body


# harness -> [(source, destination, converter, destination suffix)]; converter None copies as is
HARNESS_TARGETS = {
    "claude": [("subagents", ".claude/agents", None, None), ("skills", ".claude/skills", None, None)],
    "codex": [("subagents", ".codex/agents", to_codex, ".toml")],
    "cursor": [("subagents", ".cursor/agents", to_cursor, ".md")],
    "opencode": [("subagents", ".config/opencode/agents", to_opencode, ".md")],
}
# The copies of agent/AGENTS.md: the shared one (Claude Code imports it, Cursor's User Rules are pasted
# from it), and the harnesses that read it only as a literal copy in their own folder (no imports).
RULES_COPIES = {"shared": ".agents/AGENTS.md", "codex": ".codex/AGENTS.md", "opencode": ".config/opencode/AGENTS.md"}


def state_of(path, target, text=None):
    if not target.exists():
        return "new"
    if target.is_symlink():
        return "changed"
    if text is not None:
        return "same" if target.read_text() == text else "changed"
    return "same" if filecmp.cmp(path, target, shallow=False) else "changed"


def plugin_installs():
    """(source, destination, mode) for each file entry in the install.json of each plugin repo, skill, agent/hooks or workbench tool, and the build entries."""
    files, builds = [], []
    dirs = (
        sorted(PLUGINS.iterdir())
        if PLUGINS
        else [repo for _, repo in plugin_repos.own_repos()]
        + sorted((AGENT / "skills").iterdir())
        + [AGENT / "hooks"]
        + sorted(TOOLS.iterdir())
        + sorted(HARNESS_MODS.iterdir())
    )
    # A plugin hosted in this repo (plugins.json `path`) is also a folder under tools/; read it once.
    unique = {}
    for d in dirs:
        unique.setdefault(d.resolve(), d)
    for manifest in (d / "install.json" for d in unique.values()):
        if not manifest.is_file():
            continue
        data = json.loads(manifest.read_text())
        for entry in data.get("files", []):
            dest = HOME / entry["dest"].removeprefix("~/").removeprefix("$HOME/")
            src = manifest.parent / entry["src"]
            # Checked on the written path, before any symlink: an absolute dest or ../ must not leave home or the repo.
            for path, root, field in ((dest, HOME, "dest"), (src, manifest.parent, "src")):
                if not Path(os.path.normpath(path)).is_relative_to(os.path.normpath(root)):
                    raise SystemExit(f"{manifest}: {field} {entry[field]!r} is outside {root}")
            files.append((src, dest, int(str(entry.get("mode", "0644")), 8)))
        for entry in data.get("builds", []) + ([data] if "build" in data else []):
            builds.append((manifest.parent, entry["build"], entry.get("dest", "")))
    return files, builds


def targets(harnesses):
    """(source, destination dir or file, converter, suffix) for the shared and the selected harness targets."""
    for src_rel, dst_rel in TARGETS:
        yield AGENT / src_rel, HOME / dst_rel, None, None
    for harness in harnesses:
        for src_rel, dst_rel, convert, suffix in HARNESS_TARGETS[harness]:
            yield AGENT / src_rel, HOME / dst_rel, convert, suffix


def mapped(src, dst, convert, suffix):
    """(source file, destination file, converter) under one target."""
    files = [src] if src.is_file() else sorted(p for p in src.rglob("*") if p.is_file())
    if src == AGENT / "skills":
        files = [p for p in files if len(p.relative_to(src).parts) > 1 and not SKILL_STAYS & set(p.relative_to(src).parts)]
    for path in files:
        target = dst if src.is_file() else dst / path.relative_to(src)
        if convert:
            target = target.with_suffix(suffix)
        yield path, target, convert


@functools.cache
def committed_rules():
    """Every committed version of agent/AGENTS.md, as bytes; empty when this checkout has no git history.
    Read once per run: each rulebook copy asks for it, in both plan and the CHECK pass."""
    try:
        log = subprocess.run(["git", "-C", str(ROOT), "log", "--format=%H", "--", "agent/AGENTS.md"],
                             capture_output=True, text=True, check=True).stdout.split()
        return frozenset(subprocess.run(["git", "-C", str(ROOT), "show", f"{sha}:agent/AGENTS.md"],
                                        capture_output=True, check=True).stdout for sha in log)
    except (OSError, subprocess.CalledProcessError):
        return frozenset()


def rules_copy(which):
    """Plan entry for one copy of agent/AGENTS.md (RULES_COPIES), or None with a CHECK line when the
    file has its own content.

    The file is ours to update when it is missing, already equal to agent/AGENTS.md, or equal to a
    committed version of it (an earlier deploy's copy). Anything else is the user's: a line added by
    hand is never overwritten, including in a harness copy that matches a hand-edited shared copy.
    """
    src, dst = AGENT / "AGENTS.md", HOME / RULES_COPIES[which]
    if not dst.exists():
        return (src, dst, "new", None, None), None
    if dst.is_symlink():
        return (src, dst, "changed", None, None), None
    if filecmp.cmp(src, dst, shallow=False):
        return (src, dst, "same", None, None), None
    if dst.read_bytes() in committed_rules():
        return (src, dst, "changed", None, None), None
    if which == "shared":
        return None, (f"CHECK   {dst} has its own content, left as is. Move what every machine should "
                      f"read into agent/AGENTS.md; lines for this machine only can stay")
    name = {"codex": "Codex", "opencode": "OpenCode"}[which]
    return None, (f"CHECK   {dst} has its own content, left as is. {name} reads its literal text and "
                  f"follows no pointer, so replace it by hand with a copy of agent/AGENTS.md")


def chosen_copies(harnesses):
    """The RULES_COPIES keys deploy handles: the shared copy always, a harness copy when it is chosen."""
    return [k for k in RULES_COPIES if k == "shared" or k in harnesses]


def plan(harnesses=HARNESSES):
    """List of (source, destination, state, mode, text); text is the converted content, or None to copy."""
    items = []
    for target in targets(harnesses):
        for path, dst, convert in mapped(*target):
            text = convert(path.relative_to(AGENT), path.read_text()) if convert else None
            items.append((path, dst, state_of(path, dst, text), None, text))
    for which in chosen_copies(harnesses):
        entry, _ = rules_copy(which)
        if entry:
            items.append(entry)
    for path, dst, mode in plugin_installs()[0]:
        items.append((path, dst, state_of(path, dst), mode, None))
    return items


def extras(harnesses=HARNESSES):
    """Files at a destination directory that agent/ does not produce; reported, never removed. In a skills
    folder only the skill folders agent/skills has count: the rest (synced or plugin-made skills) are not ours."""
    for target in targets(harnesses):
        src, dst = target[0], target[1]
        if src.is_dir() and dst.is_dir():
            expected = {t for _, t, _ in mapped(*target)}
            owned = {p.name for p in src.iterdir() if p.is_dir()} if src == AGENT / "skills" else None
            for path in sorted(p for p in dst.rglob("*") if p.is_file()):
                if owned is not None and path.relative_to(dst).parts[0] not in owned:
                    continue
                if path not in expected and not path.name.endswith((".pre-deploy", ".pre-deploy.last")):
                    yield path


def checks(harnesses=HARNESSES):
    """Things deploy does not write but reports on."""
    if "claude" in harnesses:
        claude_md = HOME / ".claude/CLAUDE.md"
        if not claude_md.exists():
            yield f"MISSING {claude_md}: create it with the line {SHIM}"
        elif SHIM not in claude_md.read_text():
            yield f"CHECK   {claude_md} does not import {SHIM}"
        yield from claude_settings()
    for which in chosen_copies(harnesses):
        _, line = rules_copy(which)
        if line:
            yield line
    if "cursor" in harnesses:
        yield ("CHECK   Cursor User Rules live in Cursor Settings > Rules, not a file: "
               "paste agent/AGENTS.md there by hand (not checked here)")


def claude_settings():
    """CHECK lines for what ~/.claude/settings.json lacks: the workbench status line and the mod folders
    in CLAUDE_CODE_PLUGIN_DIRS. Settings are merged by hand, so this only reports."""
    path = HOME / ".claude/settings.json"
    try:
        settings = json.loads(path.read_text()) if path.exists() else {}
    except (OSError, ValueError):
        yield f"CHECK   {path} is not readable JSON; the status line and mods were not checked"
        return
    command = (settings.get("statusLine") or {}).get("command", "")
    if "claude-statusline" not in command:
        yield (f"CHECK   {path} does not use the workbench status line; set "
               f'"statusLine": {{"type": "command", "command": "{STATUSLINE}"}}')
    loaded = [d.strip() for d in (settings.get("env") or {}).get("CLAUDE_CODE_PLUGIN_DIRS", "").split(":") if d.strip()]
    home = str(HOME)
    missing = [d for d in MOD_DIRS if d not in loaded and d.replace("~", home, 1) not in loaded]
    if missing:
        yield (f"CHECK   {path} does not load {', '.join(missing)}; add "
               f'"CLAUDE_CODE_PLUGIN_DIRS": "{":".join(loaded + missing)}" to "env"')


def parse_harnesses(value):
    chosen = [h.strip() for h in value.split(",") if h.strip()]
    unknown = [h for h in chosen if h not in HARNESSES]
    if unknown or not chosen:
        raise argparse.ArgumentTypeError(f"unknown harness {', '.join(unknown) or value!r}; pick from {','.join(HARNESSES)}")
    return tuple(h for h in HARNESSES if h in chosen)


def main():
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--apply", action="store_true", help="copy the new and changed files")
    parser.add_argument("--harness", type=parse_harnesses, default=HARNESSES,
                        help="comma-separated harnesses to deploy for (default: claude,codex,cursor,opencode)")
    args = parser.parse_args()

    # Plan and checks are read before anything is written: the rules-copy decisions compare
    # against the ~/.agents/AGENTS.md that is on disk now.
    items, notes, found = plan(args.harness), list(checks(args.harness)), list(extras(args.harness))
    changes = 0
    for src, dst, state, mode, text in items:
        if state == "same":
            continue
        changes += 1
        label = src.relative_to(ROOT) if src.is_relative_to(ROOT) else src
        print(f"{state.upper():8} {dst}  <- {label}{' (converted)' if text is not None else ''}")
        if args.apply:
            if dst.is_symlink():
                dst.unlink()
            dst.parent.mkdir(parents=True, exist_ok=True)
            # Every overwrite saves what it replaces: the first into .pre-deploy, which is never overwritten, so the
            # file from before any deploy is kept; later ones into .pre-deploy.last, so a later hand edit is kept too.
            if dst.exists():
                first = dst.with_name(dst.name + ".pre-deploy")
                shutil.copy2(dst, first if not first.exists() else dst.with_name(first.name + ".last"))
            if text is None:
                shutil.copy2(src, dst)
            else:
                dst.write_text(text)
            if mode is not None:
                dst.chmod(mode)
    for path in found:
        print(f"EXTRA    {path}  (not from agent/; left in place)")
    for line in notes:
        print(line)
    for folder, command, dest in plugin_installs()[1]:
        where = folder.relative_to(ROOT) if folder.is_relative_to(ROOT) else folder
        print(f"BUILD    {dest}  <- {folder.name}: run `{command}` in {where} (not run here)")
    if not changes:
        print("up to date")
    elif not args.apply:
        print(f"{changes} file(s) would change; rerun with --apply to copy")
    return 0


if __name__ == "__main__":
    sys.exit(main())
